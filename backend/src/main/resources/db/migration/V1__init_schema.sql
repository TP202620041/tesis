-- =====================================================================
-- ViaSegura - Esquema inicial
-- Sistema de crowdsourcing geoespacial de infraestructura vial (Lima)
-- =====================================================================

-- Habilita el soporte geoespacial (US-05, US-09, US-11).
CREATE EXTENSION IF NOT EXISTS postgis;

-- ---------------------------------------------------------------------
-- Distrito: limites distritales como GEOGRAPHY(MultiPolygon,4326).
-- Base de la asignacion automatica por point-in-polygon (US-05).
-- ---------------------------------------------------------------------
CREATE TABLE distrito (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(120) NOT NULL UNIQUE,
    ubigeo  VARCHAR(6),
    limites geography(MultiPolygon, 4326)
);

-- Indice espacial GiST para ST_Contains(limites, punto) en la asignacion
-- automatica de distrito a cada reporte.
CREATE INDEX ix_distrito_limites_gist ON distrito USING GIST (limites);

-- ---------------------------------------------------------------------
-- Usuario (US-01, US-02, US-30).
-- distrito_id: residencia (ciudadano) o distrito de gestion (funcionario).
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                    VARCHAR(150) NOT NULL UNIQUE,
    password_hash            VARCHAR(255) NOT NULL,
    nombre                   VARCHAR(100) NOT NULL,
    apellido                 VARCHAR(100) NOT NULL,
    rol                      VARCHAR(30)  NOT NULL,
    distrito_id              BIGINT REFERENCES distrito (id),
    preferencia_notificacion VARCHAR(10)  NOT NULL DEFAULT 'AMBAS',
    activo                   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at               TIMESTAMPTZ  NOT NULL,
    updated_at               TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('CIUDADANO', 'FUNCIONARIO_MUNICIPAL', 'ADMIN'))
);

-- ---------------------------------------------------------------------
-- CategoriaDano (US-05, US-29).
-- distrito_id NULL => categoria estandar global.
-- ---------------------------------------------------------------------
CREATE TABLE categoria_dano (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL,
    descripcion VARCHAR(300),
    es_estandar BOOLEAN      NOT NULL DEFAULT FALSE,
    distrito_id BIGINT REFERENCES distrito (id),
    activo      BOOLEAN      NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------------------
-- Reporte (US-05..US-09). ubicacion GEOGRAPHY(Point,4326).
-- ---------------------------------------------------------------------
CREATE TABLE reporte (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ubicacion        geography(Point, 4326) NOT NULL,
    foto_url         VARCHAR(500),
    descripcion      VARCHAR(1000),
    categoria_id     BIGINT      NOT NULL REFERENCES categoria_dano (id),
    estado           VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    distrito_id      BIGINT REFERENCES distrito (id),
    creador_id       BIGINT      NOT NULL REFERENCES usuario (id),
    total_adhesiones INTEGER     NOT NULL DEFAULT 1,
    resolved_at      TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL,
    updated_at       TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_reporte_estado CHECK (estado IN ('PENDIENTE', 'RECIBIDO', 'EN_PROCESO', 'RESUELTO', 'RECHAZADO'))
);

-- Indice espacial GiST: deteccion de duplicados en radio 20m (US-09) y
-- mapa de calor por densidad (US-11).
CREATE INDEX ix_reporte_ubicacion_gist ON reporte USING GIST (ubicacion);
CREATE INDEX ix_reporte_distrito       ON reporte (distrito_id);
CREATE INDEX ix_reporte_estado         ON reporte (estado);
CREATE INDEX ix_reporte_categoria      ON reporte (categoria_id);

-- ---------------------------------------------------------------------
-- AdhesionReporte: N:M Usuario-Reporte por acumulacion de duplicados (US-09).
-- ---------------------------------------------------------------------
CREATE TABLE adhesion_reporte (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporte_id BIGINT      NOT NULL REFERENCES reporte (id),
    usuario_id BIGINT      NOT NULL REFERENCES usuario (id),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_adhesion_reporte_usuario UNIQUE (reporte_id, usuario_id)
);

-- ---------------------------------------------------------------------
-- HistorialEstadoReporte: auditoria de cambios de estado (US-14, US-22).
-- ---------------------------------------------------------------------
CREATE TABLE historial_estado_reporte (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporte_id      BIGINT      NOT NULL REFERENCES reporte (id),
    estado_anterior VARCHAR(20),
    estado_nuevo    VARCHAR(20) NOT NULL,
    comentario      VARCHAR(1000),
    autor_id        BIGINT REFERENCES usuario (id),
    created_at      TIMESTAMPTZ NOT NULL
);
CREATE INDEX ix_historial_reporte ON historial_estado_reporte (reporte_id);

-- ---------------------------------------------------------------------
-- AsignacionResponsable: cuadrilla/responsable interno (US-15).
-- ---------------------------------------------------------------------
CREATE TABLE asignacion_responsable (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporte_id      BIGINT       NOT NULL REFERENCES reporte (id),
    responsable     VARCHAR(150) NOT NULL,
    notas           VARCHAR(500),
    asignado_por_id BIGINT REFERENCES usuario (id),
    activo          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ  NOT NULL
);
CREATE INDEX ix_asignacion_reporte ON asignacion_responsable (reporte_id);

-- ---------------------------------------------------------------------
-- Calificacion: estrellas 1..5 tras resolucion (US-26).
-- ---------------------------------------------------------------------
CREATE TABLE calificacion (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporte_id BIGINT      NOT NULL REFERENCES reporte (id),
    usuario_id BIGINT      NOT NULL REFERENCES usuario (id),
    estrellas  INTEGER     NOT NULL,
    comentario VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_calificacion_reporte_usuario UNIQUE (reporte_id, usuario_id),
    CONSTRAINT ck_calificacion_estrellas CHECK (estrellas BETWEEN 1 AND 5)
);

-- ---------------------------------------------------------------------
-- ComentarioPublico: sobre reportes resueltos, flag reincidencia (US-27).
-- ---------------------------------------------------------------------
CREATE TABLE comentario_publico (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporte_id           BIGINT       NOT NULL REFERENCES reporte (id),
    usuario_id           BIGINT       NOT NULL REFERENCES usuario (id),
    contenido            VARCHAR(1000) NOT NULL,
    posible_reincidencia BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at           TIMESTAMPTZ  NOT NULL
);
CREATE INDEX ix_comentario_reporte ON comentario_publico (reporte_id);

-- ---------------------------------------------------------------------
-- Notificacion: multicanal push/email con estado de entrega (US-16, US-21).
-- ---------------------------------------------------------------------
CREATE TABLE notificacion (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT      NOT NULL REFERENCES usuario (id),
    reporte_id     BIGINT REFERENCES reporte (id),
    tipo_evento    VARCHAR(30) NOT NULL,
    canal          VARCHAR(10) NOT NULL,
    estado_entrega VARCHAR(10) NOT NULL DEFAULT 'PENDIENTE',
    mensaje        VARCHAR(500),
    leida          BOOLEAN     NOT NULL DEFAULT FALSE,
    sent_at        TIMESTAMPTZ,
    created_at     TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_notificacion_canal CHECK (canal IN ('PUSH', 'EMAIL')),
    CONSTRAINT ck_notificacion_entrega CHECK (estado_entrega IN ('PENDIENTE', 'ENVIADA', 'FALLIDA'))
);
CREATE INDEX ix_notificacion_usuario ON notificacion (usuario_id);

-- ---------------------------------------------------------------------
-- TicketSoporte (US-25). usuario_id opcional (consultas de visitantes).
-- ---------------------------------------------------------------------
CREATE TABLE ticket_soporte (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT REFERENCES usuario (id),
    email_contacto VARCHAR(150) NOT NULL,
    asunto         VARCHAR(200) NOT NULL,
    mensaje        VARCHAR(2000) NOT NULL,
    estado         VARCHAR(15)  NOT NULL DEFAULT 'ABIERTO',
    created_at     TIMESTAMPTZ  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_ticket_estado CHECK (estado IN ('ABIERTO', 'EN_PROCESO', 'CERRADO'))
);
