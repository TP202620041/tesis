-- ---------------------------------------------------------------------
-- V8 (US-03): recuperacion de contrasena por token de un solo uso con
-- expiracion, enviado por email. Tabla dedicada (no un campo en usuario):
-- el token es un evento de seguridad transitorio (como historial_estado_
-- reporte o notificacion), no un atributo estable de la cuenta; asi se
-- evita ensuciar "usuario" con columnas casi siempre NULL y se permite
-- conservar el historial de solicitudes de forma natural.
-- ---------------------------------------------------------------------
CREATE TABLE password_reset_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT       NOT NULL REFERENCES usuario (id),
    token      VARCHAR(100) NOT NULL,
    expires_at TIMESTAMPTZ  NOT NULL,
    used_at    TIMESTAMPTZ,
    created_at TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_password_reset_token_token UNIQUE (token)
);
CREATE INDEX ix_password_reset_token_usuario ON password_reset_token (usuario_id);
