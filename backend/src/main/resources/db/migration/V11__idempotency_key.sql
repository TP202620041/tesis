-- ---------------------------------------------------------------------
-- V11 (US-06): idempotencia real en la creacion de reportes via el
-- header HTTP Idempotency-Key. Tabla dedicada (no una columna en
-- "reporte"): la clave es un metadato del INTENTO de creacion, no un
-- atributo del reporte resultante -- un mismo reporte puede no tener
-- ninguna clave asociada (creado sin el header) y una clave puede
-- terminar resolviendose en una adhesion (US-09) en vez de un reporte
-- nuevo, asi que no existe una relacion 1:1 clave-reporte que
-- justifique una columna en "reporte".
--
-- Se escopea por (clave, usuario_id) y no solo por clave: evita que una
-- clave adivinada o reutilizada por error por otro cliente devuelva la
-- respuesta (con datos del reporte) de un usuario distinto.
--
-- Vigencia de 48h (expires_at): un reporte creado offline (Service
-- Worker) puede tardar en sincronizar; pasado ese margen, un reintento
-- con la misma clave se trata como un intento nuevo, no como el mismo
-- intento reenviado (ver IdempotencyKeyService).
-- ---------------------------------------------------------------------
CREATE TABLE idempotency_key (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave         VARCHAR(100) NOT NULL,
    usuario_id    BIGINT       NOT NULL REFERENCES usuario (id),
    response_body TEXT         NOT NULL,
    expires_at    TIMESTAMPTZ  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_idempotency_key_clave_usuario UNIQUE (clave, usuario_id)
);
CREATE INDEX ix_idempotency_key_expires_at ON idempotency_key (expires_at);
