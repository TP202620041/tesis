-- ---------------------------------------------------------------------
-- V15 (NC-01, D-09): MUNICIPALIDAD y PERIODO_GESTION del modelo de datos
-- (OB2 §5), modulo "municipalidades".
--
--   - municipalidad.distrito_id es NOT NULL UNIQUE: una municipalidad por
--     distrito (42 distritales + la Metropolitana de Lima para Cercado).
--     La geometria sigue solo en "distrito" (D-09): el reporte obtiene su
--     distrito por punto en poligono y de ahi su municipalidad.
--   - correo_contacto (canal oficial) admite nulo: se completa despues.
--
-- Las 43 filas de municipalidad NO se insertan aqui: los distritos los
-- carga DistritoSeeder al arrancar, despues de Flyway, asi que en una base
-- vacia esta migracion no tendria distritos que referenciar. Las siembra
-- municipalidades.infra.MunicipalidadSeeder, que corre despues de
-- DistritoSeeder y es idempotente.
--
-- El periodo 2023-2026 si se siembra aqui: no depende de otro dato.
--
-- GESTION_MUNICIPAL y REQUISITO_RECEPCION no se crean todavia: sus
-- columnas no estan definidas en ARCHITECTURE.md §8 (ver NC-01 en el plan).
--
-- Ninguna tabla referencia a "reporte", asi que no entran en
-- limpiezaFkSafe de los IT.
-- ---------------------------------------------------------------------
CREATE TABLE municipalidad (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    distrito_id     BIGINT       NOT NULL UNIQUE REFERENCES distrito (id),
    nombre          VARCHAR(160) NOT NULL UNIQUE,
    correo_contacto VARCHAR(255)
);

CREATE TABLE periodo_gestion (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inicio DATE NOT NULL UNIQUE,
    fecha_fin    DATE NOT NULL,
    CONSTRAINT ck_periodo_gestion_fechas CHECK (fecha_fin >= fecha_inicio)
);

