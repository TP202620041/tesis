-- ---------------------------------------------------------------------
-- V12 (NC-07): SUSCRIPCION_PUSH del modelo de datos (OB2 §5).
--
-- Una fila por navegador o dispositivo suscrito con la Push API: el
-- endpoint que entrega el servicio de push del navegador y las dos claves
-- con las que se cifra el mensaje (p256dh, auth), tal como las devuelve
-- PushSubscription.toJSON(). Un usuario puede tener varias (movil y PC).
--
-- endpoint es UNIQUE porque identifica al navegador, no a la persona: si
-- en ese navegador inicia sesion otro usuario, la fila se reasigna a el
-- (upsert por endpoint, ver SuscripcionPushService) en vez de duplicarse.
--
-- activa: la baja explicita del usuario borra la fila; "activa = false"
-- queda para el envio real (US-21), cuando el servicio de push responda
-- que la suscripcion caduco (404/410) y haya que dejar de intentarlo.
-- ---------------------------------------------------------------------
CREATE TABLE suscripcion_push (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT       NOT NULL REFERENCES usuario (id),
    endpoint    TEXT         NOT NULL,
    p256dh      VARCHAR(255) NOT NULL,
    auth        VARCHAR(255) NOT NULL,
    user_agent  VARCHAR(500),
    activa      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_suscripcion_push_endpoint UNIQUE (endpoint)
);
CREATE INDEX ix_suscripcion_push_usuario ON suscripcion_push (usuario_id);
