-- ---------------------------------------------------------------------
-- V13 (NC-07b, D-12): CONSENTIMIENTO del modelo de datos (OB2 §5).
--
-- Historial por finalidad y version, no un flag en "usuario": la Ley
-- N.° 29733 pide un consentimiento previo, expreso y revocable POR
-- FINALIDAD, y la tesis debe poder mostrar QUE acepto cada usuario,
-- CUANDO y QUE VERSION del texto.
--
--   - Cada aceptacion es una fila nueva (nunca se sobrescribe).
--   - Revocar llena revocado_en de las filas no revocadas; no se borra.
--   - Vigente = la fila mas reciente sin revocado_en para (usuario,
--     finalidad). Para TERMINOS_Y_PRIVACIDAD, ademas, la version debe
--     ser la vigente de la aplicacion (app.legal.version-terminos); eso
--     lo decide el servicio, no la tabla.
--
-- No se insertan filas para los usuarios existentes: D-12 prohibe darlos
-- por aceptados. Hasta que acepten, /me devuelve debeAceptarTerminos=true.
--
-- No referencia a "reporte", asi que no entra en limpiezaFkSafe de los IT.
-- ---------------------------------------------------------------------
CREATE TABLE consentimiento (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id        BIGINT      NOT NULL REFERENCES usuario (id),
    finalidad         VARCHAR(40) NOT NULL,
    version_documento VARCHAR(40) NOT NULL,
    aceptado_en       TIMESTAMPTZ NOT NULL,
    revocado_en       TIMESTAMPTZ,
    CONSTRAINT ck_consentimiento_finalidad CHECK (finalidad IN (
        'TERMINOS_Y_PRIVACIDAD', 'NOTIFICACIONES_PUSH', 'NOTIFICACIONES_CORREO')),
    CONSTRAINT ck_consentimiento_revocado_posterior CHECK (
        revocado_en IS NULL OR revocado_en >= aceptado_en)
);

-- "Vigente por usuario y finalidad": parcial sobre las no revocadas, que
-- es lo que consultan /me, el registro y la suscripcion push.
CREATE INDEX ix_consentimiento_vigente
    ON consentimiento (usuario_id, finalidad, aceptado_en DESC)
    WHERE revocado_en IS NULL;

-- Historial completo del usuario (GET /api/auth/me/consentimientos).
CREATE INDEX ix_consentimiento_usuario ON consentimiento (usuario_id, aceptado_en DESC);
