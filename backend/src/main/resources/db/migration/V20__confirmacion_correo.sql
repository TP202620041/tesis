-- ---------------------------------------------------------------------
-- V20 (NC-09): confirmacion del correo al crear la cuenta.
--
-- usuario.correo_confirmado: una cuenta sin confirmar no puede iniciar
-- sesion hasta abrir el enlace que recibe por correo (decision del
-- usuario, 28/10). Las cuentas que YA existen se dan por confirmadas
-- (misma decision): en produccion hay usuarios reales y ninguno debe
-- quedar fuera. Por eso la columna se agrega con DEFAULT TRUE, que llena
-- las filas existentes (en PostgreSQL 11+ sin reescribir la tabla), y
-- despues el default pasa a FALSE: toda cuenta nueva nace sin confirmar
-- salvo que quien la crea diga lo contrario (el ADMIN inicial, DEP-04).
--
-- usuario.correo_confirmado_en: cuando se confirmo. NULL en las cuentas
-- confirmadas por esta migracion.
-- ---------------------------------------------------------------------
ALTER TABLE usuario ADD COLUMN correo_confirmado BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE usuario ALTER COLUMN correo_confirmado SET DEFAULT FALSE;
ALTER TABLE usuario ADD COLUMN correo_confirmado_en TIMESTAMPTZ;

-- ---------------------------------------------------------------------
-- Tokens del enlace de confirmacion. Mismo patron que
-- password_reset_token (V8): tabla propia, un solo uso y vencimiento.
-- Diferencias:
--   - token_hash: se guarda el SHA-256 del token (hex), nunca el token.
--     Es NULL desde que se pide el correo hasta que el hilo que lo envia
--     genera el token (ConfirmacionCorreoService#emitirMensaje): el valor
--     no pasa por la peticion, ni por un evento, ni por la base.
--   - invalidated_at: pedir un enlace nuevo, o confirmar la cuenta, anula
--     los anteriores que siguen sin usar.
--
-- No referencia a "reporte", asi que no entra en limpiezaFkSafe de los IT.
-- ---------------------------------------------------------------------
CREATE TABLE token_confirmacion_correo (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT      NOT NULL REFERENCES usuario (id),
    token_hash     VARCHAR(64),
    expires_at     TIMESTAMPTZ NOT NULL,
    used_at        TIMESTAMPTZ,
    invalidated_at TIMESTAMPTZ,
    created_at     TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_token_confirmacion_correo_hash UNIQUE (token_hash)
);

-- Tope de reenvios por cuenta (cuenta por created_at) y anulacion de los
-- pendientes de una cuenta.
CREATE INDEX ix_token_confirmacion_correo_usuario
    ON token_confirmacion_correo (usuario_id, created_at);
